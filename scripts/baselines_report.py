"""Aggregate benchmark runs into the baseline table.

    python scripts/baselines_report.py outputs/bench docs/results/runs \
        --out docs/results/baselines

Reads every ``<dir>/<agent>/<task>-s<seed>.json`` written by
``scripts/run_benchmark.py`` and writes ``<out>.json`` and ``<out>.md``. Per
agent and task: episodes run, incomplete episodes, mean score over complete
episodes with a 95% bootstrap interval, the mean counting incomplete episodes
as score 0, and the pass rate. With ``--common-seeds`` a second table
restricts every agent to the seeds all of them ran.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from recruitenv.tasks import TASK_REGISTRY  # noqa: E402

TASKS = ("easy", "medium", "hard")
BOOT = 2000


def bootstrap_ci(values: list[float], seed: int = 0) -> tuple[float, float]:
    if len(values) < 2:
        return (float("nan"), float("nan"))
    rng = np.random.default_rng(seed)
    arr = np.asarray(values, dtype=float)
    means = arr[rng.integers(0, len(arr), size=(BOOT, len(arr)))].mean(axis=1)
    lo, hi = np.percentile(means, [2.5, 97.5])
    return (float(lo), float(hi))


def load(dirs: list[Path]) -> dict[str, dict[str, Any]]:
    agents: dict[str, dict[str, Any]] = {}
    for d in dirs:
        if not d.exists():
            continue
        for run in sorted(p for p in d.iterdir() if p.is_dir()):
            meta_path = run / "run.json"
            meta = json.loads(meta_path.read_text()) if meta_path.exists() else {"agent": run.name}
            entry = agents.setdefault(meta["agent"], {"meta": meta, "episodes": {}})
            for res in run.glob("*-s*.json"):
                r = json.loads(res.read_text())
                entry["episodes"][(r["task"], int(r["seed"]))] = r
    return agents


def summarise(episodes: dict, task: str, seeds: set[int] | None = None) -> dict[str, Any]:
    eps = [r for (t, s), r in episodes.items() if t == task and (seeds is None or s in seeds)]
    complete = [r for r in eps if not r.get("incomplete")]
    scores = [r["score"] for r in complete]
    thr = TASK_REGISTRY[task].success_threshold
    lo, hi = bootstrap_ci(scores)
    usage = [r.get("usage", {}) for r in eps]
    return {
        "episodes": len(eps),
        "incomplete": len(eps) - len(complete),
        "mean": float(np.mean(scores)) if scores else None,
        "ci95": [lo, hi] if scores else None,
        "mean_incomplete_as_zero": float(np.sum(scores) / len(eps)) if eps else None,
        "pass_rate": float(np.mean([s >= thr for s in scores])) if scores else None,
        "seeds": sorted(s for (t, s) in episodes if t == task and (seeds is None or s in seeds)),
        "model_calls": int(sum(u.get("calls", 0) for u in usage)),
        "completion_tokens": int(sum(u.get("completion_tokens", 0) for u in usage)),
        "prompt_tokens": int(sum(u.get("prompt_tokens", 0) for u in usage)),
        "length_cutoffs": int(sum(u.get("length_cutoffs", 0) for u in usage)),
        "api_errors": int(sum(u.get("api_errors", 0) for u in usage)),
    }


def _fmt(cell: dict[str, Any]) -> str:
    if not cell["episodes"]:
        return "—"
    if cell["mean"] is None:
        return f"all {cell['incomplete']} incomplete"
    lo, hi = cell["ci95"]
    ci = f" [{lo:.2f}, {hi:.2f}]" if lo == lo else ""
    s = f"{cell['mean']:.3f}{ci} · {cell['pass_rate']:.0%} · n={cell['episodes']}"
    if cell["incomplete"]:
        s += f" ({cell['incomplete']} incomplete; {cell['mean_incomplete_as_zero']:.3f} counting them as 0)"
    return s


def build(agents: dict[str, dict[str, Any]], common: bool) -> dict[str, Any]:
    report: dict[str, Any] = {"tasks": {t: {"threshold": TASK_REGISTRY[t].success_threshold} for t in TASKS},
                              "agents": {}}
    for name, entry in agents.items():
        report["agents"][name] = {"meta": entry["meta"],
                                  "all_seeds": {t: summarise(entry["episodes"], t) for t in TASKS}}
    if common:
        model_agents = [a for a, e in agents.items() if e["meta"].get("model")]
        for t in TASKS:
            sets = [{s for (tt, s) in agents[a]["episodes"] if tt == t} for a in (model_agents or agents)]
            shared = set.intersection(*sets) if sets else set()
            report["tasks"][t]["common_seeds"] = sorted(shared)
            for name, entry in agents.items():
                report["agents"][name].setdefault("common_seeds", {})[t] = summarise(entry["episodes"], t, shared)
    return report


def to_markdown(report: dict[str, Any]) -> str:
    lines = ["# Baselines", "",
             "Generated by `scripts/baselines_report.py` from `scripts/run_benchmark.py` runs. "
             "Each cell: mean score [95% bootstrap interval] · pass rate · episodes. "
             "Thresholds: " + ", ".join(f"{t} {report['tasks'][t]['threshold']}" for t in TASKS) + ".", ""]

    def table(key: str, title: str) -> None:
        lines.extend([f"## {title}", "", "| Agent | " + " | ".join(TASKS) + " |",
                      "|---|" + "---|" * len(TASKS)])
        for name, a in sorted(report["agents"].items(), key=lambda kv: (bool(kv[1]["meta"].get("model")), kv[0])):
            if key not in a:
                continue
            lines.append(f"| {name} | " + " | ".join(_fmt(a[key][t]) for t in TASKS) + " |")
        lines.append("")

    if any("common_seeds" in a for a in report["agents"].values()):
        seeds = {t: report["tasks"][t].get("common_seeds", []) for t in TASKS}
        table("common_seeds", "Same seeds as the models")
        lines.append("Seeds per task: " + "; ".join(f"{t} {_seedrange(seeds[t])}" for t in TASKS) + ".")
        lines.append("")
    table("all_seeds", "Every seed each agent ran")

    model_rows = [(n, a) for n, a in report["agents"].items() if a["meta"].get("model")]
    if model_rows:
        lines.extend(["## Model settings and cost", "",
                      "| Agent | Settings | Model calls | Prompt tokens | Completion tokens | Cut-off replies | API errors |",
                      "|---|---|---|---|---|---|---|"])
        for n, a in model_rows:
            cells = a["all_seeds"].values()
            st = a["meta"].get("settings", {})
            lines.append(
                f"| {n} | {', '.join(f'{k}={v}' for k, v in st.items())} | "
                f"{sum(c['model_calls'] for c in cells)} | {sum(c['prompt_tokens'] for c in cells):,} | "
                f"{sum(c['completion_tokens'] for c in cells):,} | {sum(c['length_cutoffs'] for c in cells)} | "
                f"{sum(c['api_errors'] for c in cells)} |")
        lines.append("")
    return "\n".join(lines)


def _seedrange(seeds: list[int]) -> str:
    if not seeds:
        return "none"
    if seeds == list(range(seeds[0], seeds[-1] + 1)):
        return f"{seeds[0]}–{seeds[-1]} ({len(seeds)})"
    return f"{len(seeds)} seeds"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Aggregate benchmark runs.")
    ap.add_argument("dirs", nargs="+")
    ap.add_argument("--out", default="docs/results/baselines")
    ap.add_argument("--common-seeds", action="store_true")
    args = ap.parse_args(argv)
    agents = load([Path(d) for d in args.dirs])
    report = build(agents, args.common_seeds)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(report, indent=1) + "\n")
    out.with_suffix(".md").write_text(to_markdown(report))
    print(to_markdown(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
